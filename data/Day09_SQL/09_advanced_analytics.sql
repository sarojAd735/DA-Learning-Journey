Question8
Create revenue bands:
•	< 10000 → Low Revenue
•	10000–30000 → Medium Revenue
•	30000 → High Revenue
Then calculate:
| revenue_band | total_revenue |

Answer:
select
case
when billingamount < 10000 then 'Low Revenue'
when billingamount > 10000 and billingamount < 30000 then 'Medium Revenue'
else 'High Revenue'
end as revenue_band, round(sum(billingamount), 2) as total_revenue
from healthcare.healthcare_patients
group by revenue_band
