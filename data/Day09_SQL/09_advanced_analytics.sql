Question6
For each medical condition, find the doctor who treated the most patients.

Answer:

WITH 

doctor_condition_counts AS (
    SELECT
        medicalcondition,
        doctor,
        COUNT(*) AS patient_count
    FROM healthcare.healthcare_patients
    GROUP BY medicalcondition, doctor
),
ranked_doctors AS (
    SELECT
        medicalcondition,
        doctor,
        patient_count,
        RANK() OVER (
            PARTITION BY medicalcondition
            ORDER BY patient_count DESC
        ) AS doctor_rank
    FROM doctor_condition_counts
)
SELECT
    medicalcondition,
    doctor,
    patient_count
FROM ranked_doctors
WHERE doctor_rank = 1
ORDER BY medicalcondition;
