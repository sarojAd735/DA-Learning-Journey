Question1
What percentage of total hospital revenue is generated by each admission type?
Answer: 

select admission_type, sum(billingamount) as total_revenue,
round(
(sum(billingamount) * 100 / (select sum(billingamount) from healthcare.healthcare_patients)), 2) as revenue_percentage

from healthcare.healthcare_patients
group by admission_type
